import (
	"os"
	"regexp"
	"strings"
	"testing"
)

func TestBuiltinThemesCarryTheirNotices(t *testing.T) {
	schemes := builtinSchemes()
	if len(schemes) < 10 {
		t.Fatalf("%d built-in schemes, want the full selection", len(schemes))
	}
	notices, err := os.ReadFile("themes_builtin_licenses.txt")
	if err != nil {
		t.Fatal(err)
	}
	header, err := os.ReadFile("themes_builtin_gen.go")
	if err != nil {
		t.Fatal(err)
	}
	if !regexp.MustCompile(`^// Code generated by scripts/gen_tui_themes.go from \S+ at commit [0-9a-f]{40}; DO NOT EDIT\.\n`).Match(header) {
		t.Error("the generated file lacks its header with the commit of the collection")
	}
	light := 0
	for _, s := range schemes {
		if s.Name != strings.ToLower(s.Name) {
			t.Errorf("%q: names are the lower-case names of the collection", s.Name)
		}
		if !strings.Contains(strings.ToLower(string(notices)), "\n"+s.Name+"\n  license: ") {
			t.Errorf("%q has no licence notice", s.Name)
		}
		if luminance(hexRGB(t, s.Scheme.Background)) > 0.5 {
			light++
		}
	}
	if light < 3 {
		t.Errorf("%d light schemes, want light variants kept", light)
	}
	if got, want := strings.Count(string(notices), "\n  Copyright: Copyright "), len(schemes); got != want {
		t.Errorf("%d copyright notices for %d schemes", got, want)
	}
	if !strings.Contains(string(notices), "MIT License") {
		t.Error("the licence of the collection is missing")
	}
}

// Every built-in scheme is the mix of its colours under true colour, keeps the contrast limits, and paints.
func TestBuiltinThemesKeepTheContrast(t *testing.T) {
	set := exampleSet(t)
	for _, s := range builtinSchemes() {
		t.Run(s.Name, func(t *testing.T) {
			sc, err := schemeOf(*s.Scheme)
			if err != nil {
				t.Fatal(err)
			}
			want, ok := mixPalette(sc.fg, sc.bg, &sc.ansi)
			if !ok {
				t.Fatalf("the scheme does not mix (%.2f:1)", contrast(sc.fg, sc.bg))
			}
			st := resolve(t, set, s.Name, ProfileTrueColor, nil)
			p := st.Palette()
			if p != want || !st.Paints() {
				t.Errorf("the theme is not the painted mix of its scheme")
			}
			if p.Base != s.Scheme.Background || p.Text != s.Scheme.Foreground || p.Accent != s.Scheme.ANSI[slotAccent] ||
				p.OK != s.Scheme.ANSI[slotOK] || p.Fail != s.Scheme.ANSI[slotFail] || p.Warn != s.Scheme.ANSI[slotWarn] {
				t.Errorf("roles do not follow the scheme: %+v", p)
			}
			if err := contrastError(p); err != nil {
				t.Error(err)
			}
		})
	}
}

// With 256 colours a scheme steps down to indexes, or falls back to the plain palette where the steps lose
// their contrast; with 16 colours it is the plain palette and paints nothing.
func TestBuiltinThemesFollowTheColorProfile(t *testing.T) {
	set := exampleSet(t)
	for _, s := range builtinSchemes() {
		sc, _ := schemeOf(*s.Scheme)
		mixed, _ := mixPalette(sc.fg, sc.bg, &sc.ansi)
		st := resolve(t, set, s.Name, ProfileANSI256, nil)
		if stepped, ok := steppedTo256(mixed, sc.fg, sc.bg); ok {
			if st.Palette() != stepped || !st.Paints() {
				t.Errorf("%s with 256 colours: not the painted stepped palette", s.Name)
			}
			for _, r := range stepped.roles() {
				if _, ok := r.color.index(); !ok {
					t.Errorf("%s with 256 colours: role %s = %q is no index", s.Name, r.name, *r.color)
				}
			}
		} else if st.Palette() != plainPalette() || st.Paints() {
			t.Errorf("%s with 256 colours: want the plain palette without a painted ground", s.Name)
		}
		st = resolve(t, set, s.Name, ProfileANSI16, nil)
		if st.Palette() != plainPalette() || st.Paints() {
			t.Errorf("%s with 16 colours: want the plain palette without a painted ground", s.Name)
		}
		if !st.Style(StyleActiveRow).GetReverse() {
			t.Errorf("%s with 16 colours: the selection is not reverse video", s.Name)
		}
	}
}
